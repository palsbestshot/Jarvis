/// Format an ingredient as `"hinglish (english)"` when the map has both
/// names, or just `"name"` if they're the same. Returns the key as-is
/// if unknown — this is a graceful fallback so a new ingredient can be
/// added in a dish before the alias map catches up.
String ing(String key) {
  final en = INGREDIENT_ALIASES[key];
  if (en == null) return key;
  if (en == key) return key;
  return '$key ($en)';
}

