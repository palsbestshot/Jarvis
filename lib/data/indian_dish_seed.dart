// ingredients listed in a bilingual format — "hinglish (english)", e.g.
// "pyaaz (onion)", "baingan (brinjal)" — so the picker's substring
// search matches whichever name Rakhi types.
//
// Organisation:
//   - INGREDIENT_ALIASES: canonical hinglish → english map so every dish
//     writes the same spelling for a given ingredient.
//   - ing(key): helper that returns the bilingual form, or the key as-is
//     if it's already an English word with no Hindi counterpart (e.g.
//     'paneer', 'rice').
//   - IndianDishSeed.all(): flat list of Dish objects, grouped by
//     section comments so the file stays navigable.
//   - IndianDishSeed.seedVersion: bump whenever the seed changes in a
//     breaking way. Rakhi's meals_section reads this + her saved version
//     and runs migrateDishCatalog to add missing dishes / prune legacy.
//   - IndianDishSeed.legacyNonVegIds: seed IDs from v1 that are now
//     removed (all non-veg / egg). Migration deletes these IFF they
//     still carry is_custom=false AND times_used=0 (preserving any
//     she actually used).
//
// New dish IDs all start with `seed_`. Custom user-added dishes get
// Firestore-generated IDs and carry `is_custom: true`.

